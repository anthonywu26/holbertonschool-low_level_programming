
/**
 * op_add - add 2 integers
 * @a: first number
 * @b: second number
 * Return: integer result
 */
int op_add(int a, int b)
{
	return (a + b);
}

/**
 * op_sub - subtract 2 integers
 * @a: first number
 * @b: second number
 * Return: integer result
 */
int op_sub(int a, int b)
{
	return (a - b);
}

/**
 * op_mul - multiply 2 integers
 * @a: first number
 * @b: second number
 * Return: integer result
 */
int op_mul(int a, int b)
{
	return (a * b);
}

/**
 * op_div - integer division of 2 integers
 * @a: first number
 * @b: second number
 * Return: integer result
 */
int op_div(int a, int b)
{
	return (a / b);
}

/**
 * op_mod - find remainder after integer division
 * @a: first number
 * @b: second number
 * Return: integer result
 */
int op_mod(int a, int b)
{
	return (a % b);
}
